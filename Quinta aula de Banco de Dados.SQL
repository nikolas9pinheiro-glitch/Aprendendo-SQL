      CONSTRAINT PK_CONSULTA PRIMARY KEY (CRM, COD_PAC, DTH_AGENDADO),
      CONSTRAINT FK_MEDICO_CONSULTA FOREIGN KEY (CRM) REFERENCES MEDICO(CRM),
      CONSTRAINT FK_PACIENTE_CONSULTA FOREIGN KEY (COD_PAC) REFERENCES PACIENTE(COD_PAC),
      CONSTRAINT CK_TIPO_CONSULTA CHECK (TIPO IN ('C', 'R')),
      CONSTRAINT CK_SITUACAO_CONSULTA CHECK (SITUACAO IN ('A', 'C', 'R'))
  );
   
