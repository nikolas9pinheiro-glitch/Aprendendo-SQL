/*6. TRAZER OS NOMES DE CARGOS (JOBS) QUE NUNCA FORAM USADOS EM FUNCIONARIOS */

SELECT FIRST_NAME, JOB_TITLE
FROM EMPLOYEES EMP
RIGHT JOIN JOBS JOB 
ON EMP.JOB_ID = JOB.JOB_ID
WHERE FIRST_NAME IS NULL;

-- AGRUPAMENTO DE VALORES (SOMA, CONTAGEM, MEDIA, MINIMO, MAXIMO) E ARREDONDAMENTO EM AVG (MEDIA)

SELECT 
  SUM(SALARY), 
  COUNT(SALARY), 
  ROUND (AVG(SALARY),2), --ROUND ARRENDONDA PRA CIMA E FLOAR ARREDONDA PRA BAIXO 
  MAX(SALARY), 
  MIN(SALARY)
FROM EMPLOYEES E
LEFT JOIN DEPARTMENTS D
ON E.DEPARTMENT_ID = D.DEPARTMENT_ID
GROUP BY DEPARTMENT_NAME;

