--3. TRAZER UMA LISTAGEM COM O NOME DO FUNCIONARIO, SEU E-MAIL E DEPARTAMENTO
--E O NOME DEPARTAMENTO QUE ELE TRABALHA, ORDENAR ASCENDENTE
--POR NOME DO DEPARTAMENTO

SELECT EMP.FIRST_NAME, EMP.EMAIL,DEP.DEPARTMENT_NAME
FROM EMPLOYEES EMP
LEFT JOIN DEPARTMENTS DEP 
ON EMP.DEPARTMENT_ID = DEP.DEPARTMENT_ID
ORDER BY DEP.DEPARTMENT_NAME ASC;

/*4. TRAZER UMA LISTAGEM COM O NOME DOS DEPARTAMENTOS QUE NÃO FORAM ALOCADOS A NENHUM FUNCIONARIOS*/

SELECT DEP.DEPARTMENT_NAME
FROM EMPLOYEES EMP
LEFT JOIN DEPARTMENTS DEP 
ON EMP.DEPARTMENT_ID = DEP.DEPARTMENT_ID
WHERE DEPARTMENT_NAME IS NULL;

/*5. OS FUNCIONARIOS SEM DEPARTAMENTOS*/

