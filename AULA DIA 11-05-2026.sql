--2. TRAZER UMA LISTA COM CIDADE, ESTADO E NOME DO PAIS

SELECT city, state_province, country_name
FROM locations loc
RIGHT JOIN countries cnt 
ON loc.country_id = cnt.country_id
LEFT JOIN regions reg 
ON reg.region_id = cnt.region_id
WHERE UPPER(region_name) = UPPER('americas');


